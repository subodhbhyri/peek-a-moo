// Generates src/app/core/data/timezone-locations.ts from the IANA time zone database:
//   zone1970.tab  - every zone with reference coordinates (e.g. Asia/Dubai +2518+05518)
//   backward      - alias links (e.g. Asia/Muscat -> Asia/Dubai, Asia/Calcutta -> Asia/Kolkata)
// An alias gets its canonical zone's coordinates and label. Run: node scripts/tz-locations.mjs
// Needs the internet (one request per file). Exits non-zero, writing nothing, if anything is off.
import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const BASE = 'https://data.iana.org/time-zones/tzdb/';
const out = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../src/app/core/data/timezone-locations.ts',
);

async function get(name) {
  const res = await fetch(BASE + name, { signal: AbortSignal.timeout(30_000) });
  if (res.status !== 200) {
    console.error(`tz-locations: ${BASE}${name} answered ${res.status}`);
    process.exit(1);
  }
  return (await res.text()).replace(/\r/g, '');
}

/** "+2518+05518" or "+251830+0551830" -> [lat, lon] in decimal degrees. */
function parseCoords(s) {
  const m = /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(s);
  if (!m) throw new Error(`bad coordinates "${s}"`);
  const deg = (sign, d, mi, se) =>
    (sign === '-' ? -1 : 1) * (Number(d) + Number(mi) / 60 + Number(se ?? 0) / 3600);
  return [deg(m[1], m[2], m[3], m[4]), deg(m[5], m[6], m[7], m[8])].map(
    (v) => Math.round(v * 1e4) / 1e4,
  );
}

const label = (zone) => zone.split('/').pop().replace(/_/g, ' ');

const version = (await get('version')).trim();
const zones = {};
for (const line of (await get('zone1970.tab')).split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [, coords, zone] = line.split('\t');
  const [lat, lon] = parseCoords(coords);
  zones[zone] = { lat, lon, label: label(zone) };
}

// Aliases: "Link <target> <linkname>"; the target may itself be an alias, so resolve chains.
const links = new Map();
for (const line of (await get('backward')).split('\n')) {
  if (!line.startsWith('Link')) continue;
  const parts = line.split(/\s+/);
  links.set(parts[2], parts[1]);
}
const all = { ...zones };
for (const alias of links.keys()) {
  if (zones[alias]) continue;
  let target = links.get(alias);
  for (let i = 0; i < 10 && !zones[target] && links.has(target); i++) target = links.get(target);
  if (zones[target]) all[alias] = zones[target];
}

const names = Object.keys(all).sort();
if (names.length < 300) {
  console.error(`tz-locations: only ${names.length} zones; something is wrong`);
  process.exit(1);
}
const body = names
  .map(
    (z) =>
      `  ${JSON.stringify(z)}: { lat: ${all[z].lat}, lon: ${all[z].lon}, label: ${JSON.stringify(all[z].label)} },`,
  )
  .join('\n');
await writeFile(
  out,
  `// GENERATED by scripts/tz-locations.mjs from the IANA time zone database (tzdb ${version}): zone1970.tab
// for coordinates and the "backward" file for aliases. Public domain. Do not edit by hand.
// Reference coordinates are a representative place for each zone, which is plenty for a fallback location.

export interface TimeZoneLocation {
  lat: number;
  lon: number;
  /** The zone's city part, e.g. "Dubai". */
  label: string;
}

export const TIMEZONE_LOCATIONS: Readonly<Record<string, TimeZoneLocation>> = {
${body}
};
`,
);
console.log(
  `tz-locations: wrote ${names.length} zones (${Object.keys(zones).length} canonical + aliases) from tzdb ${version}`,
);
